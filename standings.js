/* =========================================
   ELEMENTS
========================================= */

const standingsBody =
  document.getElementById("standingsBody");

const leagueTitle =
  document.getElementById("leagueTitle");

const lastUpdated =
  document.getElementById("lastUpdated");

const leagueButtons =
  document.querySelectorAll(".league-btn");


/* =========================================
   DISPLAY TABLE
========================================= */

function displayStandings(league) {

  const data = leagueData[league];

  if (!data) return;


  leagueTitle.textContent = data.name;

  standingsBody.innerHTML = "";


  data.teams.forEach((team, index) => {

    const position = index + 1;

    const row = document.createElement("tr");


    /* TOP 4 = CHAMPIONS LEAGUE */

    if (position <= 4) {
      row.classList.add("champions-row");
    }


    /* POSITIONS 5-6 = EUROPA */

    else if (position <= 6) {
      row.classList.add("europa-row");
    }


    /* LAST 3 = RELEGATION */

    else if (
      position >= data.teams.length - 2
    ) {
      row.classList.add("relegation-row");
    }


    row.innerHTML = `

      <td>
        ${position}
      </td>

      <td class="team-cell">

        <div class="team-info">

          <span class="team-number">
            ${position}
          </span>

          <span class="team-name">
            ${team[0]}
          </span>

        </div>

      </td>

      <td>${team[1]}</td>
      <td>${team[2]}</td>
      <td>${team[3]}</td>
      <td>${team[4]}</td>
      <td>${team[5]}</td>

      <td class="points">
        ${team[6]}
      </td>

    `;


    standingsBody.appendChild(row);

  });


  lastUpdated.textContent =
    "Updated just now";

}


/* =========================================
   LEAGUE BUTTONS
========================================= */

leagueButtons.forEach(button => {

  button.addEventListener("click", () => {

    leagueButtons.forEach(btn => {
      btn.classList.remove("active");
    });


    button.classList.add("active");


    const selectedLeague =
      button.dataset.league;


    displayStandings(selectedLeague);

  });

});


/* =========================================
   INITIAL LOAD
========================================= */

displayStandings("premier");